package db

import (
	"log"
)

// InitCampusSchema creates all campus operations tables if they do not exist
func InitCampusSchema() {
	tables := []string{
		`CREATE TABLE IF NOT EXISTS campus_timetable_slots (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			class_name VARCHAR(64) NOT NULL,
			day_of_week VARCHAR(16) NOT NULL,
			period_index INT NOT NULL,
			start_time VARCHAR(16) NOT NULL,
			end_time VARCHAR(16) NOT NULL,
			subject VARCHAR(128) NOT NULL,
			teacher_name VARCHAR(128) NOT NULL,
			room VARCHAR(64) NOT NULL,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_admissions_inquiries (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			applicant_name VARCHAR(128) NOT NULL,
			guardian_name VARCHAR(128) NOT NULL,
			email VARCHAR(128) NOT NULL,
			phone VARCHAR(32) NOT NULL,
			target_grade VARCHAR(64) NOT NULL,
			previous_school VARCHAR(128),
			stage VARCHAR(32) NOT NULL DEFAULT 'Inquiry',
			tour_date VARCHAR(32),
			notes TEXT,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_fee_structures (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			class_level VARCHAR(64) NOT NULL,
			term VARCHAR(32) NOT NULL,
			tuition_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
			development_levy NUMERIC(12,2) NOT NULL DEFAULT 0,
			ict_stem_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
			exam_materials_fee NUMERIC(12,2) NOT NULL DEFAULT 0,
			total_due NUMERIC(12,2) NOT NULL DEFAULT 0,
			due_date VARCHAR(32),
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_student_invoices (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			student_id VARCHAR(64) NOT NULL,
			student_name VARCHAR(128) NOT NULL,
			class_name VARCHAR(64) NOT NULL,
			term VARCHAR(32) NOT NULL,
			session VARCHAR(32) NOT NULL,
			total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
			amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0,
			balance NUMERIC(12,2) NOT NULL DEFAULT 0,
			status VARCHAR(32) NOT NULL DEFAULT 'UNPAID',
			payment_reference VARCHAR(128),
			paid_at TIMESTAMP WITH TIME ZONE,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_library_books (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			title VARCHAR(255) NOT NULL,
			author VARCHAR(128) NOT NULL,
			isbn VARCHAR(64),
			category VARCHAR(64) NOT NULL,
			total_copies INT NOT NULL DEFAULT 1,
			available_copies INT NOT NULL DEFAULT 1,
			shelf_location VARCHAR(64),
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_library_loans (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			book_id VARCHAR(64) NOT NULL,
			borrower_id VARCHAR(64) NOT NULL,
			borrower_name VARCHAR(128) NOT NULL,
			borrower_type VARCHAR(32) NOT NULL DEFAULT 'STUDENT',
			borrowed_date VARCHAR(32) NOT NULL,
			due_date VARCHAR(32) NOT NULL,
			return_date VARCHAR(32),
			status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_inventory_items (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			item_name VARCHAR(128) NOT NULL,
			category VARCHAR(64) NOT NULL,
			current_stock INT NOT NULL DEFAULT 0,
			reorder_threshold INT NOT NULL DEFAULT 5,
			unit_price NUMERIC(12,2) NOT NULL DEFAULT 0,
			location VARCHAR(64),
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_procurement_requests (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			requested_by VARCHAR(128) NOT NULL,
			department VARCHAR(64) NOT NULL,
			title VARCHAR(128) NOT NULL,
			estimated_cost NUMERIC(12,2) NOT NULL DEFAULT 0,
			status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
			approval_notes TEXT,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_transport_routes (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			route_name VARCHAR(128) NOT NULL,
			vehicle_plate VARCHAR(32) NOT NULL,
			driver_name VARCHAR(128) NOT NULL,
			driver_phone VARCHAR(32) NOT NULL,
			capacity INT NOT NULL DEFAULT 30,
			enrolled_students INT NOT NULL DEFAULT 0,
			corridor_areas TEXT,
			status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_hostel_allocations (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			hostel_name VARCHAR(128) NOT NULL,
			gender VARCHAR(16) NOT NULL,
			room_number VARCHAR(32) NOT NULL,
			bed_number VARCHAR(32) NOT NULL,
			student_id VARCHAR(64),
			student_name VARCHAR(128),
			class_name VARCHAR(64),
			guardian_phone VARCHAR(32),
			session VARCHAR(32) NOT NULL,
			term VARCHAR(32) NOT NULL,
			status VARCHAR(32) NOT NULL DEFAULT 'OCCUPIED',
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_notices_and_events (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			title VARCHAR(255) NOT NULL,
			category VARCHAR(64) NOT NULL,
			body TEXT NOT NULL,
			event_date VARCHAR(32),
			target_audience VARCHAR(64) NOT NULL DEFAULT 'ALL',
			is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_messages (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			sender_name VARCHAR(128) NOT NULL,
			sender_role VARCHAR(64) NOT NULL,
			recipient_group VARCHAR(64) NOT NULL,
			subject VARCHAR(255) NOT NULL,
			message TEXT NOT NULL,
			channel VARCHAR(32) NOT NULL DEFAULT 'PORTAL',
			sent_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_mobile_app_accounts (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			user_id VARCHAR(64) NOT NULL,
			full_name VARCHAR(128) NOT NULL,
			role VARCHAR(32) NOT NULL,
			device_type VARCHAR(32),
			push_token VARCHAR(255),
			last_active TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_homework_and_assessments (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			title VARCHAR(255) NOT NULL,
			class_name VARCHAR(64) NOT NULL,
			subject VARCHAR(128) NOT NULL,
			due_date VARCHAR(32) NOT NULL,
			instructions TEXT NOT NULL,
			max_score NUMERIC(5,2) NOT NULL DEFAULT 10,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_academic_sessions (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			session_name VARCHAR(64) NOT NULL,
			academic_year VARCHAR(32) NOT NULL,
			start_date VARCHAR(32) NOT NULL,
			end_date VARCHAR(32) NOT NULL,
			is_current BOOLEAN NOT NULL DEFAULT FALSE,
			status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
			terms_count INT NOT NULL DEFAULT 3,
			description TEXT,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_academic_terms (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			session_id VARCHAR(64) NOT NULL,
			term_name VARCHAR(64) NOT NULL,
			term_alias VARCHAR(64),
			term_order INT NOT NULL DEFAULT 1,
			is_current BOOLEAN NOT NULL DEFAULT FALSE,
			status VARCHAR(32) NOT NULL DEFAULT 'UPCOMING',
			resumption_date VARCHAR(32),
			mid_term_break_start VARCHAR(32),
			mid_term_break_end VARCHAR(32),
			exams_start_date VARCHAR(32),
			exams_end_date VARCHAR(32),
			vacation_date VARCHAR(32),
			teaching_days INT NOT NULL DEFAULT 65,
			weeks_count INT NOT NULL DEFAULT 13,
			ca1_start_date VARCHAR(32),
			ca1_end_date VARCHAR(32),
			ca1_submission_deadline VARCHAR(32),
			ca2_start_date VARCHAR(32),
			ca2_end_date VARCHAR(32),
			ca2_submission_deadline VARCHAR(32),
			terminal_exam_submission_deadline VARCHAR(32),
			broadsheet_approval_date VARCHAR(32),
			results_release_date VARCHAR(32),
			notes TEXT,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_calendar_events (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			session_id VARCHAR(64) NOT NULL,
			term_id VARCHAR(64),
			title VARCHAR(128) NOT NULL,
			category VARCHAR(64) NOT NULL DEFAULT 'ACADEMIC',
			start_date VARCHAR(32) NOT NULL,
			end_date VARCHAR(32),
			is_statutory_holiday BOOLEAN NOT NULL DEFAULT FALSE,
			description TEXT,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_classes (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			name VARCHAR(64) NOT NULL,
			level_order INT NOT NULL DEFAULT 1,
			category VARCHAR(32) NOT NULL DEFAULT 'SECONDARY',
			curriculum VARCHAR(64) DEFAULT 'NERDC / WAEC Standard',
			description TEXT,
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_class_arms (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			class_id VARCHAR(64) NOT NULL REFERENCES campus_classes(id) ON DELETE CASCADE,
			name VARCHAR(64) NOT NULL,
			arm_code VARCHAR(32),
			form_teacher_id VARCHAR(64),
			form_teacher_name VARCHAR(128),
			room_number VARCHAR(64),
			capacity INT NOT NULL DEFAULT 35,
			enrolled_students INT NOT NULL DEFAULT 0,
			status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS campus_class_students (
			id VARCHAR(64) PRIMARY KEY,
			tenant_id VARCHAR(64) NOT NULL,
			arm_id VARCHAR(64) NOT NULL REFERENCES campus_class_arms(id) ON DELETE CASCADE,
			student_id VARCHAR(64) NOT NULL,
			student_name VARCHAR(128) NOT NULL,
			admission_number VARCHAR(64) NOT NULL,
			gender VARCHAR(16) NOT NULL,
			status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
			created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE INDEX IF NOT EXISTS idx_campus_classes_tenant ON campus_classes(tenant_id, level_order)`,
		`CREATE INDEX IF NOT EXISTS idx_campus_arms_tenant ON campus_class_arms(tenant_id, class_id)`,
		`CREATE INDEX IF NOT EXISTS idx_campus_students_arm ON campus_class_students(tenant_id, arm_id)`,
	}

	for _, stmt := range tables {
		if _, err := DB.Exec(stmt); err != nil {
			log.Printf("⚠️ [service_campuspro] Table creation warning: %v", err)
		}
	}
	log.Println("⚡ [service_campuspro] Schema initialized successfully")
}
